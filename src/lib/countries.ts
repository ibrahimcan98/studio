export function normalizeCountrySearch(value: string): string {
  return value
    .toLocaleLowerCase('tr-TR')
    .replace(/ı/g, 'i')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9+]+/g, ' ')
    .trim();
}

export function countryMatchesSearch(country: CountryCode, search: string): boolean {
  const normalizedSearch = normalizeCountrySearch(search);
  if (!normalizedSearch) return true;

  const searchableText = normalizeCountrySearch(
    `${country.country} ${ENGLISH_COUNTRY_NAMES[country.code] ?? ''}`
  );

  return searchableText.includes(normalizedSearch) || country.code.includes(search.trim());
}
